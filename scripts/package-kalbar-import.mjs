import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";

// Offline SQL packaging. Never connects to hosted/local Postgres or reads env.
// SQL approval fields stay unset so copying a file cannot silently approve data.
const directory = "data/reference/kalbar-big";
try {
  const bytes = readFileSync(`${directory}/districts.geojson`);
  const review = z
    .object({
      sha256: z.string().regex(/^[a-f0-9]{64}$/),
      source: z.literal(
        "https://geoservices.big.go.id/rbi/rest/services/Hosted/Wilayah_Administrasi_Kabupaten__Kota/FeatureServer/0",
      ),
    })
    .parse(JSON.parse(readFileSync(`${directory}/review.json`, "utf8")));
  if (createHash("sha256").update(bytes).digest("hex") !== review.sha256)
    throw new Error(
      "Snapshot hash changed; download and review again before packaging.",
    );
  const point = z.tuple([
    z.number().finite().min(-180).max(180),
    z.number().finite().min(-90).max(90),
  ]);
  const ring = z.array(point).min(4);
  const polygon = z.array(ring).min(1);
  const { features } = z
    .object({
      type: z.literal("FeatureCollection"),
      features: z
        .array(
          z.object({
            properties: z.object({
              kdpkab: z.string().regex(/^61\.\d{2}$/),
              namobj: z.string().min(1).max(200),
              kdppum: z.literal("61"),
              wadmpr: z.literal("Kalimantan Barat"),
            }),
            geometry: z.discriminatedUnion("type", [
              z.object({ type: z.literal("Polygon"), coordinates: polygon }),
              z.object({
                type: z.literal("MultiPolygon"),
                coordinates: z.array(polygon).min(1),
              }),
            ]),
          }),
        )
        .length(14),
    })
    .parse(JSON.parse(bytes.toString("utf8")));
  if (new Set(features.map((f) => f.properties.kdpkab)).size !== 14)
    throw new Error("Expected 14 unique district codes.");
  const quote = (value) => `'${value.replaceAll("'", "''")}'`;
  const stage = `create temporary table fireops_boundary_candidates (
 code text primary key, name text not null,
 geom extensions.geometry(MultiPolygon,4326) not null
) on commit drop;
insert into fireops_boundary_candidates(code,name,geom) values
${features.map((f) => `(${quote(f.properties.kdpkab)},${quote(f.properties.namobj)},extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson(${quote(JSON.stringify(f.geometry))}),4326)))`).join(",\n")};
`;
  const diagnostics = `select code,name,(extensions.st_isvaliddetail(geom)).valid as geometry_valid,
 (extensions.st_isvaliddetail(geom)).reason as geometry_issue,
 extensions.st_isempty(geom) as geometry_empty,
 extensions.st_npoints(geom) as vertices
from fireops_boundary_candidates order by code;
-- Interior overlaps only: shared edges do not count as overlaps.
-- Run the overlap query only if every geometry is valid.
do $review_geometry$
begin
 if exists(select 1 from fireops_boundary_candidates where not extensions.st_isvalid(geom)) then
  raise exception 'INVALID_SOURCE_GEOMETRY: review source; do not silently repair';
 end if;
end $review_geometry$;
select a.code as district_a,b.code as district_b
from fireops_boundary_candidates a join fireops_boundary_candidates b
 on a.code<b.code and a.geom && b.geom
where extensions.st_relate(a.geom,b.geom,'2********');
`;
  const header = `-- GENERATED by pnpm boundaries:package. Source BIG September 2023.
-- Snapshot SHA256: ${review.sha256}
-- Source: ${review.source}
-- Never changes incident decisions, RLS or roles. No fake NASA points.
-- Explicit optional approver-area grants in import.sql are off by default.
-- No geometry repair/simplification is performed. Target must be reviewed.
`;
  writeFileSync(
    `${directory}/review.sql`,
    `${header}
-- DATA PREFLIGHT ONLY: temporary tables, then rollback. No catalogue import.
begin;
set local statement_timeout = '120s';
${stage}
${diagnostics}
select p.id,p.role,p.status,(u.email_confirmed_at is not null and not coalesce(u.is_anonymous,false)) as verified
from public.profiles p join auth.users u on u.id=p.id
where p.role='admin' and p.status='active';
rollback;
`,
  );
  writeFileSync(
    `${directory}/import.sql`,
    `${header}
-- Do NOT run before review.sql succeeds and usage/agency approval is recorded.
-- Edit ONLY the four review fields below. No approval is prefilled.
begin;
set local statement_timeout = '120s';
select pg_advisory_xact_lock(hashtextextended('fireops-live-boundary-import',0));
create temporary table fireops_boundary_approval (
 approved_by uuid, usage_terms text, catalogue_approved boolean, grant_approver_districts boolean
) on commit drop;
insert into fireops_boundary_approval values (
 NULL, -- UUID of an existing verified, active administrator who approved this catalogue
 NULL, -- Actual license/usage permission reference (1..500 characters), NOT a guessed license
 false, -- Set true only after source, edition, terms and geometry review are complete
 false -- Optional initial area setup: true explicitly grants this approver all 14 imported districts
);
do $require_approval$
declare a fireops_boundary_approval;
begin
 select * into strict a from fireops_boundary_approval;
 if a.approved_by is null or a.catalogue_approved is distinct from true
  or a.usage_terms is null or length(btrim(a.usage_terms)) not between 1 and 500 then
  raise exception 'REVIEW_REQUIRED: fill actual approver, usage permission and explicit approval';
 end if;
 perform p.id from public.profiles p join auth.users u on u.id=p.id
 where p.id=a.approved_by and p.role='admin' and p.status='active'
 and u.email_confirmed_at is not null and not coalesce(u.is_anonymous,false)
 for share of p,u;
 if not found then
  raise exception 'VERIFIED_ADMIN_REQUIRED: choose an authorized existing administrator; this file does not bootstrap roles';
 end if;
end $require_approval$;
create temporary table fireops_previous_approver_grants on commit drop as
select coalesce(jsonb_agg(g.district_code order by g.district_code),'[]'::jsonb) as codes
from public.profile_district_grants g join fireops_boundary_approval a on a.approved_by=g.user_id;
${stage}
${diagnostics}
lock table public.districts in share row exclusive mode;
do $validate_catalogue$
begin
 if (select count(*) from fireops_boundary_candidates)<>14
  or exists(select 1 from fireops_boundary_candidates where extensions.st_isempty(geom)
    or not extensions.st_isvalid(geom) or extensions.st_srid(geom)<>4326) then
  raise exception 'INVALID_CATALOGUE: no import performed';
 end if;
 if exists(select 1 from fireops_boundary_candidates a join fireops_boundary_candidates b
  on a.code<b.code and a.geom && b.geom where extensions.st_relate(a.geom,b.geom,'2********')) then
  raise exception 'OVERLAPPING_DISTRICTS: review source; no arbitrary district assignment';
 end if;
 if exists(select 1 from public.districts d join fireops_boundary_candidates c on c.code=d.code) then
  raise exception 'CATALOGUE_ALREADY_PRESENT: no existing boundary will be overwritten';
 end if;
 if exists(select 1 from public.districts d join fireops_boundary_candidates c on c.geom && d.geometry
  where d.data_mode='live' and extensions.st_relate(c.geom,d.geometry,'2********')) then
  raise exception 'EXISTING_CATALOGUE_OVERLAP: review existing live boundaries first';
 end if;
end $validate_catalogue$;
insert into public.districts(code,province_code,name,geometry,source,source_url,license,boundary_version,data_mode,approved_by,approved_at)
select c.code,'61',c.name,c.geom,'Badan Informasi Geospasial — Wilayah Administrasi Kabupaten/Kota',
 ${quote(review.source)},btrim(a.usage_terms),${quote(`BIG-2023-09:${review.sha256}`)},'live',a.approved_by,now()
from fireops_boundary_candidates c cross join fireops_boundary_approval a;
-- Explicit operator setup only; normal app self-grant RPC restrictions remain intact.
insert into public.profile_district_grants(user_id,district_code,granted_by)
select a.approved_by,c.code,a.approved_by from fireops_boundary_candidates c
cross join fireops_boundary_approval a where a.grant_approver_districts is true
on conflict(user_id,district_code) do nothing;
insert into public.access_audit_logs(actor_id,subject_id,reason,before_state,after_state)
select approved_by,approved_by,'Approved West Kalimantan boundary catalogue import',
 jsonb_build_object('action','boundary_catalogue_import','candidate_codes_absent',true,
 'district_codes',(select codes from fireops_previous_approver_grants)),
 jsonb_build_object('action','boundary_catalogue_import','source',${quote(review.source)},'sha256',${quote(review.sha256)},
 'imported_district_codes',(select jsonb_agg(code order by code) from fireops_boundary_candidates),
 'district_codes',(select coalesce(jsonb_agg(g.district_code order by g.district_code),'[]'::jsonb)
   from public.profile_district_grants g where g.user_id=approved_by),
 'grant_approver_districts',grant_approver_districts,'data_mode','live','usage_terms',btrim(usage_terms))
from fireops_boundary_approval;
select code,name,data_mode,boundary_version,approved_at from public.districts
where code in(select code from fireops_boundary_candidates) order by code;
commit;
`,
  );
  console.log(
    "Prepared review.sql (temporary preflight) and import.sql (explicit approval required) in data/reference/kalbar-big/.",
  );
  console.log(
    "No database contacted. No env, approval, account role or district access was changed.",
  );
} catch (error) {
  console.error(
    error instanceof z.ZodError
      ? "Boundary snapshot/metadata failed validation. Prepare the source again."
      : error instanceof Error
        ? error.message
        : "Boundary SQL packaging failed.",
  );
  process.exitCode = 1;
}

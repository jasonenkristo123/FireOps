import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

// Offline only: assemble reviewed migrations; never connects to any database.
const names = readdirSync("supabase/migrations")
  .filter((name) => /^\d{14}_[a-z0-9_]+\.sql$/.test(name))
  .sort();
if (!names.length) throw new Error("No migrations found");
const parts = [
  `-- GENERATED by pnpm db:prepare-hosted. Canonical source: supabase/migrations/.
-- INITIAL INSTALL ONLY: review and execute in the intended project's Supabase SQL Editor.
-- This file creates tables/functions/policies and a PRIVATE evidence bucket.
-- No demo data, operational roles, real boundaries or secrets are included.
-- Existing FireOps tables/history cause an abort. For upgrades use Supabase CLI.
begin;
select pg_advisory_xact_lock(hashtextextended('fireops-initial-schema',0));
do $fireops_guard$
begin
 if exists(select 1 from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relname in ('profiles','profile_district_grants','access_audit_logs','districts','hotspot_observations','incidents','incident_observations','ingest_runs','teams','team_members','assignments','verification_decisions','priority_assessments','reports','evidence_files','incident_events','notifications')) then
  raise exception 'FIREOPS_ALREADY_PRESENT: use reviewed incremental migrations instead';
 end if;
end $fireops_guard$;
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations(version text primary key,statements text[],name text);
`,
];
for (const name of names) {
  const text = readFileSync(`supabase/migrations/${name}`, "utf8");
  const hash = createHash("sha256").update(text).digest("hex");
  const [version, ...rest] = name.slice(0, -4).split("_");
  if (text.includes("$fireops_source$"))
    throw new Error("SQL dollar-quote collision");
  parts.push(
    `-- ${name} SHA256 ${hash}\n${text}\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('${version}','${rest.join("_")}',array[$fireops_source$${text}$fireops_source$]);\n`,
  );
}
parts.push("notify pgrst, 'reload schema';\ncommit;\n");
mkdirSync("supabase/setup", { recursive: true });
writeFileSync("supabase/setup/initial-schema.sql", parts.join("\n"));
console.log(
  `Prepared supabase/setup/initial-schema.sql from ${names.length} migrations. No database contacted.`,
);

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// Offline packaging only. Never reads credentials or connects to a database.
const name = "20261016000800_operational_completion.sql";
const source = readFileSync(`supabase/migrations/${name}`, "utf8");
if (source.includes("$fireops_upgrade_source$"))
  throw new Error("SQL delimiter collision");
const digest = createHash("sha256").update(source).digest("hex");
const sql = `-- GENERATED by pnpm db:prepare-upgrade. Review before executing in the intended hosted Supabase SQL Editor.
-- Incremental upgrade 008 ONLY; do not use the initial installer on an existing database.
-- Source: ${name} SHA256 ${digest}
-- Adds schema/functions/indexes. No reset, deletes, real data, credentials, administrator bootstrap or NASA call.
begin;
select pg_advisory_xact_lock(hashtextextended('fireops-upgrade-008',0));
do $fireops_upgrade_guard$
begin
 if to_regclass('public.teams') is null or to_regclass('public.incidents') is null
  or to_regprocedure('private.incident_allowed(uuid,boolean)') is null
  or to_regprocedure('public.staff_roster()') is null
  or not exists(select 1 from information_schema.columns where table_schema='public'
    and table_name='verification_decisions' and column_name='incident_version') then
  raise exception 'FIREOPS_UPGRADE_PREREQUISITES: review and apply foundation/workflow migrations through 006 first';
 end if;
 if exists(select 1 from information_schema.columns where table_schema='public' and table_name='teams'
   and column_name in ('row_version','base_latitude','base_longitude','base_source','base_recorded_at','base_location'))
   or to_regprocedure('public.district_features(public.data_mode)') is not null
   or to_regprocedure('public.operations_summary(public.data_mode,timestamp with time zone,text,text)') is not null
   or to_regprocedure('public.eligible_assignees(uuid)') is not null
   or to_regprocedure('public.ingestion_status(public.data_mode)') is not null
   or to_regprocedure('public.create_report_incident(jsonb)') is not null
   or to_regprocedure('public.update_team_details(uuid,bigint,jsonb)') is not null then
  raise exception 'FIREOPS_008_ALREADY_OR_PARTIALLY_PRESENT: do not rerun; inspect current schema and migration history';
 end if;
end $fireops_upgrade_guard$;
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations(version text primary key,statements text[],name text);
do $fireops_upgrade_history$
begin
 if exists(select 1 from supabase_migrations.schema_migrations where version='20261016000800') then
  raise exception 'FIREOPS_008_HISTORY_MISMATCH: history already records 008 but its schema is incomplete; review instead of overwriting';
 end if;
end $fireops_upgrade_history$;

${source}

insert into supabase_migrations.schema_migrations(version,name,statements)
values('20261016000800','operational_completion',array[$fireops_upgrade_source$${source}$fireops_upgrade_source$]);
notify pgrst,'reload schema';
commit;
`;
mkdirSync("supabase/setup", { recursive: true });
writeFileSync("supabase/setup/upgrade-008.sql", sql);
console.log(
  "Prepared guarded incremental supabase/setup/upgrade-008.sql offline. No database contacted.",
);
